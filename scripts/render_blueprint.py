def render(manifest: dict) -> str:
    sections = (
        "Additional foundations", "Manuscript correspondence",
        "Introduction cross-references",
    )
    nodes = manifest["nodes"]
    unknown = {node["group"] for node in nodes} - set(sections)
    if unknown:
        raise ValueError(f"Unknown blueprint sections: {sorted(unknown)}")
    pending = [node for node in nodes if node["status"] in {"planned", "notready"}]
    coverage_status = (
        f"{len(pending)} mathematical entries still have pending proof obligations."
        if pending else "All mathematical entries in the audited blueprint are formalized."
    )
    parts = [INTRODUCTION.replace("@COVERAGE_STATUS@", coverage_status)]
    auxiliary_number = 0
    for section in sections:
        parts.append(r"\section{" + section + "}\n")
        section_nodes = [node for node in nodes if node["group"] == section]
        if section != "Additional foundations":
            section_nodes.sort(key=lambda node: node["source"]["line"])
        for node in section_nodes:
            environment = node["kind"]
            if environment not in {"definition", "lemma", "corollary", "proposition", "theorem", "remark"}:
                raise ValueError(f"Unsupported environment: {environment}")
            source = node["source"]
            number = source["paper_number"]
            if number is None:
                auxiliary_number += 1
                number = f"A{auxiliary_number}"
            if source["environment"] == "equation":
                environment = "equationresult"
            checked = node["status"] == "formalized"
            names = node["lean_declarations"]
            main_result = node["id"] == manifest["target"]["node"]
            title = ("Main result: " if main_result else "") + node["title"]
            # Override only the printed number; retain the internal counter so
            # PDF anchors remain unique even when lemma and equation numbers agree.
            header = r"\renewcommand{\thetheorem}{" + text_escape(number) + "}\n"
            header += f"\\begin{{{environment}}}[{text_escape(title)}]\n"
            header += "\\label{" + node["id"] + "}\n"
            if node["proved_in_manuscript"]:
                header += "\\manuscriptproof\n"
            if main_result:
                graph_label = manifest["target"].get("graph_label", node["title"])
                header += "\\mainresult{" + text_escape(graph_label) + "}\n"
            if node["status"] == "notready":
                header += "\\notready\n"
            if checked:
                if not names:
                    raise ValueError(f"Checked node has no declarations: {node['id']}")
                header += "\\lean{" + ",".join(names) + "}\n\\leanok\n"
            if node["statement_dependencies"]:
                header += "\\uses{" + ",".join(node["statement_dependencies"]) + "}\n"
            header += node["statement_tex"] + f"\n\\end{{{environment}}}\n"
            parts.append(header)

            if source["paper_number"]:
                origin = f"Paper {source['environment']} {source['paper_number']}"
            elif source["environment"] == "equation":
                origin = "Paper equation " + node["id"]
            else:
                origin = "Auxiliary foundation"
            meta = "\\noindent\\textit{" + text_escape(origin) + ". Source:} "
            meta += "\\texttt{" + text_escape(f"{source['path']}:{source['line']}") + "}.\n"
            meta += "\\textit{Status:} \\texttt{" + node["status"] + "}. "
            meta += "Main proof path.\n" if node["main_path"] else "Additional manuscript coverage.\n"
            if node["proved_in_manuscript"]:
                meta += "\\textit{Proof supplied in manuscript.}\n"
            if names:
                prefix = "Checked" if checked else "Planned"
                meta += f"\\textit{{{prefix} Lean declarations:}} "
                meta += ", ".join(declaration_text(name) for name in names) + ".\n"
            else:
                meta += "No independent Lean declaration is assigned to this expository note.\n"
            if node["notes"]:
                meta += "\\textit{Formalization note:} " + text_escape(node["notes"]) + "\n"
            parts.append(meta)

            if node["proof_plan_tex"] or node["proof_dependencies"]:
                proof = "\\begin{proof}\n\\proves{" + node["id"] + "}\n"
                if checked:
                    proof += "\\leanok\n"
                elif node["status"] == "notready":
                    proof += "\\notready\n"
                if node["proof_dependencies"]:
                    proof += "\\uses{" + ",".join(node["proof_dependencies"]) + "}\n"
                proof += "\\textit{Checked proof.} " if checked else "\\textit{Planned proof.} "
                proof += node["proof_plan_tex"] + "\n\\end{proof}\n"
                parts.append(proof)
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated content without writing it")
    parser.add_argument("--manifest", type=Path, default=ROOT / "blueprint/manifest.json")
    parser.add_argument("--output", type=Path, default=ROOT / "blueprint/src/content.tex")
    args = parser.parse_args()
    manifest = json.loads(args.manifest.read_text())
    content = render(manifest)
    if args.check:
        if not args.output.exists() or args.output.read_text() != content:
            print("Blueprint content is stale; run python3 scripts/render_blueprint.py")
            return 1
        print("Blueprint content matches manifest.")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content)
    output = args.output.resolve()
    try:
        display = output.relative_to(ROOT)
    except ValueError:
        display = output
    print(f"Rendered {len(manifest['nodes'])} blueprint nodes to {display}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
